// Command stubdoc writes docs/reference/stub-coverage.md: one table per shipped
// stub file and package, with every rule's target, verb and value. The page is
// generated from the stub files that are embedded in the binary, so it cannot
// describe a rule that the analyzers do not read.
//
// Usage, from the repository root (or through go generate in stubs/):
//
//	go run ./internal/cmd/stubdoc [-o docs/reference/stub-coverage.md]
//
// The test of this package fails when the committed page differs from the
// output of render, so a change to a stub file must be followed by a run of
// this command.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"sort"
	"strings"

	"github.com/effectgo/effectgo/internal/stubs"
	shipped "github.com/effectgo/effectgo/stubs"
)

// outPath is the page the command writes, relative to the repository root.
const outPath = "docs/reference/stub-coverage.md"

func main() {
	out := flag.String("o", outPath, "output file")
	flag.Parse()
	data, err := render()
	if err != nil {
		fmt.Fprintln(os.Stderr, "stubdoc:", err)
		os.Exit(1)
	}
	if err := os.WriteFile(*out, data, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "stubdoc:", err)
		os.Exit(1)
	}
}

// render returns the page for the shipped stub files. The output depends only
// on the files, never on the time or the environment.
func render() ([]byte, error) {
	files, err := shipped.Files()
	if err != nil {
		return nil, err
	}
	var b bytes.Buffer
	b.WriteString("---\n")
	b.WriteString("title: Stub coverage\n")
	b.WriteString("description: \"Generated list of every target that the shipped stub files cover, with its verb and value, grouped by stub file and by package.\"\n")
	b.WriteString("---\n\n")
	b.WriteString("This page is generated by `go run ./internal/cmd/stubdoc` from the shipped stub files, and a test fails when it is out of date. Edit the stub files, not this page. The rules, their syntax and the discovery order are in [Stub files](stubs.md).\n\n")
	b.WriteString("Each row is one rule. `Line` is the line of the rule in its stub file, where the source of the rule is cited in a comment. Values are as the analyzers read them: an effect list, an error variant list, an HTTP status, a route method with its argument indexes, a sink with its argument indexes, or an errdefault policy.\n")

	for _, f := range files {
		rules, err := stubs.Parse(f.Name, f.Data)
		if err != nil {
			return nil, err
		}
		writeFile(&b, f.Name, rules)
	}
	return b.Bytes(), nil
}

// writeFile writes the section of one stub file: a summary line, then one table
// per package in name order, rules in file order.
func writeFile(b *bytes.Buffer, name string, rules []stubs.Rule) {
	groups := map[string][]stubs.Rule{}
	for _, r := range rules {
		pkg := packageOf(r)
		groups[pkg] = append(groups[pkg], r)
	}
	pkgs := make([]string, 0, len(groups))
	for p := range groups {
		pkgs = append(pkgs, p)
	}
	sort.Strings(pkgs)

	fmt.Fprintf(b, "\n## `%s`\n\n", name)
	fmt.Fprintf(b, "%d rules, grouped under %d package heading(s).\n", len(rules), len(pkgs))
	for _, p := range pkgs {
		fmt.Fprintf(b, "\n### `%s`\n\n", p)
		b.WriteString("| Target | Verb | Value | Line |\n")
		b.WriteString("|---|---|---|---|\n")
		for _, r := range groups[p] {
			fmt.Fprintf(b, "| `%s` | `%s` | `%s` | %d |\n", targetOf(r), r.Verb, value(r), r.Line)
		}
	}
}

// packageOf names the package a rule is about: the package of its target, or
// the predeclared error type for (error) targets.
func packageOf(r stubs.Rule) string {
	if r.Target.Pkg == "" {
		return "predeclared (error)"
	}
	return r.Target.Pkg
}

// targetOf renders the target of a rule in stub syntax. An errdefault rule
// names a package, not a declared target, so its target is the package path.
func targetOf(r stubs.Rule) string {
	t := r.Target
	switch {
	case r.Verb == stubs.VerbErrdefault:
		return t.Pkg
	case !t.Method && t.Name == "" && t.Type != "":
		// a type target, (pkgpath.Type): a status type or a named func type
		if t.Pkg == "" {
			return "(" + t.Type + ")"
		}
		return "(" + t.Pkg + "." + t.Type + ")"
	}
	return t.String()
}

// value renders the value of a rule as the analyzers read it. Route and sink
// rules keep their argument indexes in Args; the other verbs keep their value
// in Value.
func value(r stubs.Rule) string {
	switch r.Verb {
	case stubs.VerbRoute:
		return fmt.Sprintf("%s; path argument %s; handler argument %s", r.Value, r.Args[0], r.Args[1])
	case stubs.VerbSink:
		s := "status argument " + r.Args[0]
		if r.Args[1] != "-1" {
			s += "; body argument " + r.Args[1]
		}
		return strings.TrimSpace(s)
	default:
		return r.Value
	}
}
