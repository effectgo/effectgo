func TestContractFingerprintCLI(t *testing.T) {
	bin := buildEffectgo(t)
	dir := t.TempDir()
	runtimeDir, err := filepath.Abs("../../rt")
	if err != nil {
		t.Fatal(err)
	}
	write := func(name, body string) {
		t.Helper()
		path := filepath.Join(dir, name)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write("go.mod", fmt.Sprintf("module example.com/fingerprint\n\ngo 1.26.0\n\nrequire github.com/effectgo/effectgo/rt v0.0.0\nreplace github.com/effectgo/effectgo/rt => %s\n", filepath.ToSlash(runtimeDir)))
	model := "package dto\ntype Item struct { Name string `json:\"name\"` }\n"
	write("dto/model.go", model)
	routes := `package app
import (
 "context"
 "example.com/fingerprint/dto"
 "github.com/effectgo/effectgo/rt/web"
)
func Item(context.Context, web.NoInput) (dto.Item, error) { return dto.Item{}, nil }
func Register(r *web.Router) { web.Get(r, "/item", Item) }
`
	write("routes.go", routes)
	generateIn := func(target string, patterns ...string) string {
		t.Helper()
		args := append([]string{"ts", "-o", "api.gen.ts"}, patterns...)
		_, stderr, code := runIn(t, bin, target, args...)
		if code != 0 {
			t.Fatalf("generate: exit %d: %s", code, stderr)
		}
		body, err := os.ReadFile(filepath.Join(target, "api.gen.ts"))
		if err != nil {
			t.Fatal(err)
		}
		return string(body)
	}
	generate := func() string {
		t.Helper()
		return generateIn(dir, "./...")
	}
	check := func(want int, files ...string) {
		t.Helper()
		args := append([]string{"contract", "fingerprint", "--check"}, files...)
		stdout, stderr, code := runIn(t, bin, dir, args...)
		if code != want || stdout != "" || want == 1 && !strings.Contains(stderr, "stale contract fingerprint") {
			t.Fatalf("check: exit %d, want %d; stdout=%s stderr=%s", code, want, stdout, stderr)
		}
	}
	original := generate()
	if !strings.Contains(original, "// contract-fingerprint: sha256:") || strings.Contains(original, "effectgo-inputs") {
		t.Fatal("generation must retain the contract hash without source inputs")
	}
	if got := generate(); got != original {
		t.Fatal("two generations produced different bytes")
	}
	relocated := filepath.Join(t.TempDir(), "nested", "checkout")
	if err := os.CopyFS(relocated, os.DirFS(dir)); err != nil {
		t.Fatal(err)
	}
	if got := generateIn(relocated, "./..."); got != original {
		t.Fatal("checkout path changed generated bytes")
	}
	if got := generateIn(relocated, filepath.Join(relocated, "...")); got != original {
		t.Fatal("absolute package selection changed generated bytes")
	}
	write("internal/store/auth.go", "package store\n// Unrelated storage documentation.\n")
	check(0)
	if got := generate(); got != original {
		t.Fatal("comment in another package changed generated bytes")
	}
	write("internal/store/auth.go", "package store\nfunc Unrelated() int { return 1 }\n")
	check(0)
	if got := generate(); got != original {
		t.Fatal("unrelated function in another package changed generated bytes")
	}
	check(0) // discovery
	check(0, "api.gen.ts")

	write("new.go", "package app\nfunc Unrelated() int { return 1 }\n")
	check(0)
	write("new.go", "package app\nfunc Unrelated() int { return 2 }\n")
	check(0)
	write("routes.go", strings.Replace(routes, "return dto.Item{}, nil", "return dto.Item{Name: \"changed\"}, nil", 1))
	check(0)
	write("routes.go", "// Formatting and comments do not change the contract.\n"+strings.ReplaceAll(routes, "web.Get(r,", "web.Get( r,"))
	check(0)
	write("routes.go", routes)
	write("dto/model.go", "package dto\n// DTO documentation.\ntype Item struct{ Name string `json:\"name\"` }\n")
	check(0)
	write("dto/model.go", model)
	write("routes.go", strings.Replace(routes, "func Register", "func Other(context.Context, web.NoInput) (dto.Item, error) { return dto.Item{}, nil }\nfunc Register", 1))
	check(0)
	write("routes.go", strings.Replace(strings.Replace(routes, "func Register", "func Other(context.Context, web.NoInput) (dto.Item, error) { return dto.Item{}, nil }\nfunc Register", 1), "\"/item\", Item", "\"/item\", Other", 1))
	check(1)
	write("routes.go", routes)
	for _, changed := range []string{
		strings.Replace(model, "Name string", "Label string", 1),
		strings.Replace(model, "Name string", "Name int", 1),
	} {
		write("dto/model.go", changed)
		check(1)
		generate()
		check(0)
		write("dto/model.go", model)
		generate()
	}
	write("other/routes.go", strings.ReplaceAll(strings.Replace(routes, "package app", "package other", 1), "/item", "/other"))
	check(1) // The original ./... selection must discover newly added route packages.
	generateIn(dir, ".")
	check(0) // A scoped client excludes the other package's routes.
	write("other/routes.go", strings.ReplaceAll(strings.Replace(routes, "package app", "package other", 1), "/item", "/changed-other"))
	check(0)
	generate()
	check(0)
	write("other/routes.go", strings.ReplaceAll(strings.Replace(routes, "package app", "package other", 1), "/item", "/other"))
	check(1)
	subdir := filepath.Join(dir, "other")
	generateIn(subdir, ".")
	check(0, "other/api.gen.ts")
	if err := os.Remove(filepath.Join(subdir, "api.gen.ts")); err != nil {
		t.Fatal(err)
	}
	original = generate()

	// Invalid source cannot establish that the analyzed contract is current.
	write("dto/model.go", "package dto\nthis is not valid Go\n")
	check(1)
	body, _ := os.ReadFile(filepath.Join(dir, "api.gen.ts"))
	if string(body) != original {
		t.Fatal("freshness check rewrote the generated client")
	}
	write("dto/model.go", strings.Replace(model, "Name string", "Added bool `json:\"added\"`; Name string", 1))
	check(1)
	regenerated := generate()
	if regenerated == original || !strings.Contains(regenerated, "added: Schema.Boolean") {
		t.Fatal("regeneration did not include the imported DTO field")
	}
	check(0)

	write("routes.go", strings.Replace(routes, "/item", "/renamed", 1))
	check(1)
	write("routes.go", routes)
	check(0)
	write("new.go", "package app\nconst Added = true\n")
	check(0)
	if err := os.Remove(filepath.Join(dir, "new.go")); err != nil {
		t.Fatal(err)
	}
	check(0)
	if err := os.Remove(filepath.Join(dir, "dto/model.go")); err != nil {
		t.Fatal(err)
	}
	check(1)
}

func TestGeneratedClientUnrelatedPackageStableBytes(t *testing.T) {
	bin := buildEffectgo(t)
	dir := t.TempDir()
	runtimeDir, err := filepath.Abs("../../rt")
	if err != nil {
		t.Fatal(err)
	}
	write := func(name, body string) {
		t.Helper()
		path := filepath.Join(dir, name)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write("go.mod", fmt.Sprintf("module example.com/stable\n\ngo 1.26.0\n\nrequire github.com/effectgo/effectgo/rt v0.0.0\nreplace github.com/effectgo/effectgo/rt => %s\n", filepath.ToSlash(runtimeDir)))
	write("routes.go", `package stable
import (
 "context"
 "github.com/effectgo/effectgo/rt/web"
)
type Item struct { Name string }
func Get(context.Context, web.NoInput) (Item, error) { return Item{}, nil }
func Register(r *web.Router) { web.Get(r, "/item", Get) }
`)
	write("internal/store/auth.go", "package store\n")
	generate := func() string {
		t.Helper()
		_, stderr, code := runIn(t, bin, dir, "ts", "-o", "api.gen.ts", "./...")
		if code != 0 {
			t.Fatalf("generate: exit %d: %s", code, stderr)
		}
		body, err := os.ReadFile(filepath.Join(dir, "api.gen.ts"))
		if err != nil {
			t.Fatal(err)
		}
		return string(body)
	}
	original := generate()
	for _, source := range []string{
		"package store\n// Unrelated storage documentation.\n",
		"package store\nfunc Unrelated() int { return 1 }\n",
	} {
		write("internal/store/auth.go", source)
		if got := generate(); got != original {
			t.Fatal("unrelated package edit changed generated client bytes")
		}
	}
}
