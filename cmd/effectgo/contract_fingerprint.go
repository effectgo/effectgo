package main

import (
	"errors"
	"flag"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"strings"

	"github.com/effectgo/effectgo/internal/stubs"
	"github.com/effectgo/effectgo/tsgen"
)

func runContractFingerprint(args []string) int {
	flags := flag.NewFlagSet("effectgo contract fingerprint", flag.ContinueOnError)
	check := flags.Bool("check", false, "fail if a generated client has stale contract inputs")
	output := flags.String("o", "", "generated TypeScript file to check (default: discover generated files)")
	if err := flags.Parse(args); err != nil {
		if errors.Is(err, flag.ErrHelp) {
			return 0
		}
		return 2
	}
	if err := checkFlagOrder("contract fingerprint", flags, args); err != nil {
		fmt.Fprintln(os.Stderr, err)
		return 2
	}
	root := stubs.ModuleRoot(".")
	if root == "" {
		fmt.Fprintln(os.Stderr, "effectgo contract fingerprint: run from the generating Go module")
		return 1
	}
	files := flags.Args()
	if *output != "" {
		files = append([]string{*output}, files...)
	}
	if len(files) == 0 {
		err := filepath.WalkDir(".", func(path string, entry fs.DirEntry, err error) error {
			if err != nil {
				return err
			}
			if entry.IsDir() {
				if entry.Name() == "node_modules" || entry.Name() == ".git" {
					return filepath.SkipDir
				}
				if path != "." {
					if _, err := os.Stat(filepath.Join(path, "go.mod")); err == nil {
						return filepath.SkipDir
					}
				}
				return nil
			}
			if !strings.HasSuffix(path, ".ts") {
				return nil
			}
			body, err := os.ReadFile(path)
			if err != nil {
				return err
			}
			if strings.HasPrefix(string(body), "// Code generated by effectgo ts.") {
				files = append(files, path)
			}
			return nil
		})
		if err != nil {
			fmt.Fprintf(os.Stderr, "effectgo contract fingerprint: %v\n", err)
			return 1
		}
	}
	if len(files) == 0 {
		fmt.Fprintln(os.Stderr, "effectgo contract fingerprint: no generated TypeScript files found; generate with effectgo ts first")
		return 1
	}
	code := 0
	for _, file := range files {
		body, err := os.ReadFile(file)
		var digest string
		if err == nil {
			digest, err = tsgen.CheckFingerprint(root, body)
		}
		if err != nil {
			fmt.Fprintf(os.Stderr, "effectgo contract fingerprint: %s: %v\n", file, err)
			code = 1
			continue
		}
		if !*check {
			fmt.Printf("%s sha256:%s\n", file, digest)
		}
	}
	return code
}
